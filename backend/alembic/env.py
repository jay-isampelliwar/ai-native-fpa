"""Alembic configuration, reading its connection from the application settings.

The database URL is taken from ``app.core.config`` rather than from ``alembic.ini``. A
migration that can point at a different database than the application is a migration that
will eventually be applied to the wrong one, and keeping the URL in a version controlled
ini file would also put a password there.

``target_metadata`` is the application's own metadata with every ORM module imported, which
is what makes ``alembic revision --autogenerate`` able to see drift. The initial revision
is deliberately not autogenerated - it applies the reviewed DDL - but every revision after
it is, and autogenerate is only trustworthy if the metadata is complete.

Migrations run synchronously, but on the ``psycopg`` driver rather than the default
``psycopg2`` SQLAlchemy would otherwise reach for. The project installs psycopg 3 for the
async path, and pulling in a second, older driver purely for migrations would mean the
schema is applied by a client the application never uses.

Type comparison is enabled so a column changing from ``NUMERIC(14,2)`` to something else is
caught. For a financial schema that is the drift most worth failing on.
"""

from alembic import context
from sqlalchemy import engine_from_config, pool

from app.core.config import get_settings
from app.db import models  # noqa: F401
from app.db.session import Base

config = context.config

def migration_url() -> str:

    """Put the configured URL on the psycopg 3 driver, the same client the application connects with."""

    url = get_settings().DATABASE_URL

    if url.startswith("postgresql+"):
        return url

    return url.replace("postgresql://", "postgresql+psycopg://", 1)


config.set_main_option("sqlalchemy.url", migration_url())

target_metadata = Base.metadata


def run_migrations_offline() -> None:

    """Emit SQL to stdout without a connection, for reviewing a migration before it runs."""

    context.configure(
        url=config.get_main_option("sqlalchemy.url"),
        target_metadata=target_metadata,
        literal_binds=True,
        compare_type=True,
        dialect_opts={"paramstyle": "named"},
    )

    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:

    """Connect and apply migrations in one transaction, failing the whole step on any error."""

    connectable = engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )

    with connectable.connect() as connection:

        context.configure(
            connection=connection,
            target_metadata=target_metadata,
            compare_type=True,
        )

        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()

else:
    run_migrations_online()
