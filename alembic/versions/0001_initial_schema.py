"""Create every table, enum and index of the planner schema.

This first revision applies reviewed DDL from ``0001_initial_schema.sql`` rather than
autogenerated operations. The schema was designed and argued over as SQL - the check
constraints in particular say things that are clearer in SQL than in operation calls - and
applying that exact text means the reviewed file and the migrated database cannot differ.

Every revision after this one is autogenerated from the ORM metadata in the normal way.
This is the seam between "here is the schema we agreed on" and "here is how it changed".

The downgrade drops the schema wholesale. There is nothing to preserve below the first
revision, and a partial teardown that leaves enum types behind makes the next upgrade fail
on a database that looks empty.

Revision ID: 0001
Revises:
"""

from pathlib import Path

from alembic import op

revision = "0001"
down_revision = None
branch_labels = None
depends_on = None

DDL_PATH = Path(__file__).with_suffix(".sql")

DROP_ORDER = [
    "insurance_policies",
    "retirement_assets",
    "investment_transactions",
    "holdings",
    "deposits",
    "goal_fundings",
    "goals",
    "sip_records",
    "emi_records",
    "liabilities",
    "expense_transactions",
    "expense_records",
    "income_records",
    "pending_approvals",
    "audit_records",
    "users",
]

DROP_TYPES = ["approval_status", "holding_kind", "deposit_kind", "sip_status", "frequency"]


def upgrade() -> None:

    """Apply the reviewed DDL exactly as written, so the file and the database cannot diverge."""

    op.execute(DDL_PATH.read_text())


def downgrade() -> None:

    """Drop every table and enum this revision created, leaving nothing for the next upgrade to trip on."""

    for table in DROP_ORDER:
        op.execute(f"DROP TABLE IF EXISTS {table} CASCADE")

    for type_name in DROP_TYPES:
        op.execute(f"DROP TYPE IF EXISTS {type_name}")
